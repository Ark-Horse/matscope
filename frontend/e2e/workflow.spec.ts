import {test,expect} from '@playwright/test'
import path from 'node:path'

test('material exploration, crystal and diffraction workflow',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'从结构出发，发现材料的可能'})).toBeVisible()
  await expect(page.getByTestId('crystal-viewer').locator('canvas')).toBeVisible()
  await page.screenshot({path:'../docs/screenshots/explorer.png',fullPage:true})
  await page.getByRole('button',{name:'进入结构工作台'}).click()
  await expect(page.getByRole('heading',{name:'看见材料的微观秩序'})).toBeVisible()
  await page.getByRole('button',{name:'切换超胞'}).click()
  await expect(page.getByText('2 × 2 × 2 超胞')).toBeVisible()
  const oldParameters=await page.locator('.parameter-summary').innerText()
  await page.getByLabel('晶格尺度').focus()
  await page.getByLabel('晶格尺度').press('ArrowRight')
  await page.getByRole('button',{name:'应用几何变化'}).click()
  await expect(page.locator('.parameter-summary')).not.toHaveText(oldParameters)
  await expect(page.getByText(/Cu Kα₁.*晶格尺度 101%/)).toBeVisible()
  await page.screenshot({path:'../docs/screenshots/crystal.png',fullPage:true})
  await page.getByRole('button',{name:'衍射分析',exact:true}).click()
  await page.getByRole('button',{name:'加载加噪演示谱'}).click()
  await expect(page.locator('.candidate')).toHaveCount(5)
  await expect(page.locator('.candidate').first()).toContainText('Si')
  await page.screenshot({path:'../docs/screenshots/diffraction.png',fullPage:true})
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('upload, independent prediction and saved report',async({page})=>{
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'从结构出发，发现材料的可能'})).toBeVisible()
  await page.getByRole('button',{name:'晶体结构',exact:true}).click()
  await page.locator('input[type=file]').setInputFiles(path.resolve('../data/examples/silicon.cif'))
  await expect(page.locator('.context-bar')).toContainText('uploaded')
  await page.getByRole('button',{name:'性能预测',exact:true}).click()
  await page.getByLabel('独立测试样本').selectOption({index:1})
  await expect(page.getByText('独立测试样本',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'预测当前材料'}).click()
  await expect(page.getByRole('button',{name:'打开预测报告'})).toBeVisible()
  await page.screenshot({path:'../docs/screenshots/prediction.png',fullPage:true})
  const popupPromise=page.waitForEvent('popup')
  await page.getByRole('button',{name:'打开预测报告'}).click()
  const popup=await popupPromise
  await expect(popup.getByRole('heading',{level:1})).toContainText('弹性性质预测')
  await page.getByRole('button',{name:'衍射分析',exact:true}).click()
  await page.getByLabel('上传衍射谱').setInputFiles(path.resolve('../data/examples/silicon_simulated_noisy.csv'))
  await expect(page.locator('.candidate')).toHaveCount(5)
  await page.getByRole('button',{name:'分析记录',exact:true}).click()
  await expect(page.locator('.history-list')).toContainText('弹性性质预测')
  await expect(page.locator('.history-list')).toContainText('上传谱图候选检索')
})

test('filter, CSV export and invalid upload',async({page})=>{
  await page.goto('/')
  await page.getByLabel('搜索材料').fill('TiO2')
  await expect(page.locator('.material-table tbody tr')).toHaveCount(1)
  await expect(page.locator('.material-table tbody tr').first()).toContainText('Ti')
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出数据',exact:true}).click()
  expect((await downloadPromise).suggestedFilename()).toBe('matscope-materials.csv')
  await page.getByRole('img',{name:'材料密度与体积模量散点图'}).hover()
  const imageDownload=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出图像：材料密度与体积模量散点图'}).click()
  expect((await imageDownload).suggestedFilename()).toMatch(/\.png$/)
  await page.getByRole('button',{name:'衍射分析',exact:true}).click()
  await page.getByLabel('上传衍射谱').setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from('this is invalid')})
  await expect(page.getByRole('alert')).toContainText('数据点')
})

test('mobile workspace stays within the viewport',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'从结构出发，发现材料的可能'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(391)
  await page.getByRole('button',{name:'衍射分析',exact:true}).click()
  await expect(page.getByRole('heading',{name:'解读每一条衍射指纹'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(391)
})
